// ---- Derived helpers ----

export const platformsOf = (p) => {
  const out = [];
  if (p.web) out.push({ key: "web", label: "Web", icon: "icon-link", href: p.web });
  if (p.ios) out.push({ key: "ios", label: "iOS", icon: "icon-appleinc", href: p.ios });
  if (p.android)
    out.push({ key: "android", label: "Android", icon: "icon-googleplay", href: p.android });
  if (p.github)
    out.push({ key: "github", label: "Code", icon: "icon-github", href: p.github });
  return out;
};

export const isLive = (p) => Boolean(p.web);
export const hasMobile = (p) => Boolean(p.ios || p.android);

export const matchesFilter = (p, key) => {
  if (key === "all") return true;
  if (key === "mobile") return hasMobile(p);
  return p.stack.includes(key);
};

